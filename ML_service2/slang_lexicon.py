"""
MeetupLog AI Service - 신조어/줄임말 정규화
==================================
"꿀잼", "노잼", "핵망", "인생영화", "존잼", "ㄹㅇ", "ㅇㅈ" 같은 인터넷 신조어는
GENRE_KEYWORDS / MOOD_KEYWORDS / INTENSITY_MODIFIERS 어디에도 걸리지 않아
관련성 판별과 극성 추출에서 통째로 누락된다.

신조어는 매일 새로 생기기 때문에 "사전에 다 등록하기"는 애초에 완결될 수
없는 접근이다. 그래서 두 층으로 나눈다.

  1) 고정 사전(SLANG_FIXED): "인생영화", "띵작", "극혐"처럼 불규칙하게
     쓰이는 대표 표현 - 신규 유행어가 나올 때마다 이 딕셔너리만 갱신하면 됨.
  2) 생산적 패턴(정규식): "핵/개/존/극/갓" 같은 강조 접두어 + "잼" 계열처럼
     조합이 매우 규칙적인 신조어 계열은 접두어+어근 패턴으로 일반화해서,
     사전에 없는 새 조합("존잼", "개잼", "핵잼"...)도 커버한다.

정규화 결과는 원문 대신 "완전 재밌음", "별로임" 같은 기존 강도부사(config의
INTENSITY_MODIFIERS)/부정마커(NEGATION_MARKERS) 어휘로 치환되기 때문에,
nlp_pipeline.py의 절 분리·부정 스코핑·강도 반영 로직을 그대로 재사용할 수 있다.
"""

from __future__ import annotations

import re
from typing import Tuple

# ---------------------------------------------------------------------------
# 1) 초성/이니셜 축약어
# ---------------------------------------------------------------------------
INITIALISMS = {
    "ㄹㅇㄹㅇ": "완전 진짜",
    "ㄹㅇ": "진짜",
    "ㅇㅈ?": "인정",
    "ㅇㅈ": "인정",
}

# ---------------------------------------------------------------------------
# 2) 불규칙 고정 표현 (신규 유행어는 여기에 추가)
# ---------------------------------------------------------------------------
SLANG_FIXED = {
    # 재미 계열 불규칙 표현 (규칙 패턴 대상은 아래 정규식이 처리)
    "노잼": "별로임 재미없음",
    "핵노잼": "완전 별로임 재미없음",
    "존노잼": "완전 별로임 재미없음",
    "개노잼": "완전 별로임 재미없음",
    # 평가/명작 계열
    "인생영화": "완전 최고인 영화",
    "인생작": "완전 최고인 작품",
    "갓띵작": "완전 최고인 작품",
    "띵작": "완전 좋은 작품",
    "망작": "완전 별로인 작품",
    "핵망": "완전 별로임",
    "핵실망": "완전 별로임",
    # 호불호 계열
    "극호": "완전 좋아함",
    "극혐": "완전 싫어함",
    "취저": "완전 내 취향임",
    "취향저격": "완전 내 취향임",
    "노답": "별로임",
    "구림": "별로임",
    "구려": "별로임",
    # 감탄 계열
    "쩐다": "완전 대박임",
    "쩔어": "완전 대박임",
    "미쳤다": "완전 대박임",
}

# ---------------------------------------------------------------------------
# 3) 생산적 패턴: 강조 접두어 + "잼" 계열
# ---------------------------------------------------------------------------
# 예: 꿀잼/핵잼/존잼/개잼(긍정) vs 노잼/핵노잼(부정, 위 고정사전에서 이미 처리)
_INTENSIFYING_PREFIXES = "핵|개|존|극|갓"
_JAM_PATTERN = re.compile(rf"(?:{_INTENSIFYING_PREFIXES})?꿀?잼")


def _expand_jam(match: re.Match) -> str:
    token = match.group(0)
    has_prefix = bool(re.match(rf"^(?:{_INTENSIFYING_PREFIXES})", token))
    phrase = "재밌음"
    return f"완전 {phrase}" if has_prefix or "꿀" in token else phrase


# ---------------------------------------------------------------------------
# 정규화 진입점
# ---------------------------------------------------------------------------

def normalize_slang(text: str) -> Tuple[str, bool]:
    """신조어를 기존 강도부사/부정마커 어휘로 치환한다.
    반환값: (정규화된 텍스트, 신조어 반응이 감지되었는지 여부)
    두 번째 값은 "완전 꿀잼ㅋㅋ"처럼 대상(장르/영화) 없이 반응만 있는 메시지를
    Focus(직전 화제)에 연결할지 판단하는 데 쓰인다.
    """
    result = text
    had_slang = False

    for k in sorted(INITIALISMS, key=len, reverse=True):
        if k in result:
            result = result.replace(k, INITIALISMS[k])

    for k in sorted(SLANG_FIXED, key=len, reverse=True):
        if k in result:
            result = result.replace(k, SLANG_FIXED[k])
            had_slang = True

    if _JAM_PATTERN.search(result):
        had_slang = True
        result = _JAM_PATTERN.sub(_expand_jam, result)

    return result, had_slang
